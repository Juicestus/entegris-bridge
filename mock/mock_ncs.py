def blocks_to_samples(blocks):
    """the samples a list of blocks stands for, as unsigned words"""
    samples = []
    for block in blocks:
        if block[0] == "run":
            samples += [block[1] & 0xFFFF] * block[2]
        elif block[0] == "delta":
            value = block[1]
            samples.append(value & 0xFFFF)
            for delta in block[2]:
                value -= delta
                samples.append(value & 0xFFFF)
        else:
            samples += [value & 0xFFFF for value in block[1]]
    return samples


def blocks_to_words(blocks):
    """the encoded words for a list of blocks"""
    words = []
    for block in blocks:
        if block[0] == "run":
            words += [0x10000 - block[2], block[1] & 0xFFFF]
        elif block[0] == "delta":
            deltas = block[2]
            assert all(-16 <= d <= 15 for d in deltas)
            words += [0x4000 + len(deltas), block[1] & 0xFFFF]
            padded = deltas + [0] * (-len(deltas) % 3)
            for i in range(0, len(padded), 3):
                a, b, c = padded[i:i + 3]
                words.append(((a & 0x1F) << 10) | ((b & 0x1F) << 5) | (c & 0x1F))
        else:
            words += [len(block[1])] + [value & 0xFFFF for value in block[1]]
    return words


